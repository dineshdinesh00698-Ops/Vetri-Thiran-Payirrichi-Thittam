import io
import re
from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
from fpdf import FPDF

def sanitize_text(text: str) -> str:
    replacements = {
        "“": '"', "”": '"', "‘": "'", "’": "'",
        "–": "-", "—": "-", "•": "-",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", text).strip()

def format_docx(text: str, doc_type: str) -> bytes:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(11)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run(doc_type.upper())
    run.bold = True
    run.font.name = "Times New Roman"
    run.font.size = Pt(16)

    for block in text.split("\n"):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(6)
        p.add_run(block)

    footer = doc.sections[0].footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.add_run("Generated by LegalEase")

    stream = io.BytesIO()
    doc.save(stream)
    return stream.getvalue()

class LegalEasePDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 10)
        self.cell(0, 8, "LegalEase", align="C")
        self.ln(8)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.cell(0, 10, "Generated by LegalEase", align="C")

def format_pdf(text: str, doc_type: str) -> bytes:
    pdf = LegalEasePDF()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.multi_cell(0, 10, sanitize_text(doc_type.upper()), align="C")
    pdf.ln(4)

    pdf.set_font("Helvetica", size=11)
    for block in sanitize_text(text).split("\n"):
        pdf.multi_cell(0, 7, block)
        pdf.ln(1)

    return bytes(pdf.output(dest="S"))
